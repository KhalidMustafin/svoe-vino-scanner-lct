#: Обратный указатель «фраза → вид», собирается один раз.
_LOOKUP: dict[str, str] = {}
for _kind, _phrases in KINDS.items():
    for _phrase in _phrases:
        _LOOKUP.setdefault(normalize(_phrase), _kind)


def detect(question: str) -> str | None:
    """Вид обиходной фразы, если вопрос целиком ею и является; иначе `None`."""
    return _LOOKUP.get(normalize(question or ""))


def reply(kind: str) -> str:
    """Ответ в тон обиходной фразе."""
    return TEXTS.get(kind, TEXTS["help"])
