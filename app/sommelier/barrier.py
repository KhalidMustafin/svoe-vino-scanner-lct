def _harmless(topic: str, text: str) -> str:
    """Текст без безобидных сочетаний слов темы (`_HARMLESS`)."""
    for pattern in _HARMLESS.get(topic, ()):
        text = pattern.sub(" ", text)
    return " ".join(text.split())


def _habitual_drinking(text: str, words: list[str]) -> bool:
    """«Пью каждый день по бутылке», «третий день пьём без остановки», «пью по выходным — это
    уже привычка?» — питьё привычкой."""
    if _MORNING_DRINK_RE.search(text) or _EXCESS_RE.search(text):
        return True
    if not _DRINK_SELF_RE.search(text) and not any(w.startswith("бухаю") for w in words):
        return False
    if _STRONG_FREQUENCY_RE.search(text):
        return True
    return bool(_WEAK_FREQUENCY_RE.search(text)) and any(
        word.startswith(_HABIT_MEASURE) for word in words
    )


def _bottle_dose(text: str, words: list[str]) -> bool:
    """«Две бутылки на одного за вечер», «ящик в неделю», «бутылка на двоих — не перебор?»."""
    if _MODERATE_RE.search(text):
        return True
    if not _AMOUNT_RE.search(text):
        return False
    if _PER_STRONG_RE.search(text):
        return True
    return bool(_PER_WEAK_RE.search(text)) and any(
        word.startswith(_HABIT_MEASURE) for word in words
    )


def _hangover(text: str, words: list[str]) -> bool:
    """Похмелье и утро после: «после вчерашнего мутит», «чем поправиться», «чтобы наутро»."""
    if _MORNING_AFTER_RE.search(text) or _RECOVER_RE.search(text) or _FLUSH_RE.search(text):
        return True
    if _HIT_HEAD_RE.search(text):
        return True
    if _HEAD_PAIN_RE.search(text) and any(word.startswith(_HANGOVER_CUE) for word in words):
        return True
    return not _HANGOVER_SIGNS.isdisjoint(words) and any(
        word.startswith(_HANGOVER_CUE) for word in words
    )


def _hiding(text: str, words: list[str]) -> str | None:
    """Прятки питья: от родителей и учителей — возраст, от жены и всех — зависимость."""
    if not _HIDE_RE.search(text) or not _HIDE_OBJECT_RE.search(text):
        return None
    if any(word.startswith(_GIFT) for word in words):
        return None  # подарок прячут до праздника
    return "minors" if _HIDE_FROM_ELDERS_RE.search(text) else "addiction"


def _person_age(text: str) -> bool:
    """Возраст моложе восемнадцати будущим временем или у любого человека (проверка 25.09):
    «мне в июне будет семнадцать», «студентке колледжа 16 лет», «из 10Б»."""
    for regex in (_FUTURE_AGE_RE, _PERSON_AGE_RE, _EACH_AGE_RE):
        for match in regex.finditer(text):
            years = _years_of(match.group(1), _AGE_NUMBERS)
            if years is None or years > 18:
                continue
            if regex is not _FUTURE_AGE_RE and years == 18:
                continue  # «гостю 18» — уже можно; «будет 18» — ещё нет
            rest = text[match.end() :].lstrip()
            if _wine_age_follows(text, match.end()) or rest.startswith(_COUNT_NOUNS):
                continue  # «гостям пять бутылок», «другу два бокала» — счёт, а не возраст
            return True
    return _CLASS_LETTER_RE.search(text) is not None


def _school_age(text: str, words: list[str]) -> bool:
    """Школа и ровесники без взрослого повода: «я ещё в школе», «мы с одноклассниками»."""
    adult = (
        any(word.startswith(_SCHOOL_ADULT) for word in words)
        or _TEACHER_SELF_RE.search(text) is not None
        or _ADULT_SELF_AGE_RE.search(text) is not None
    )
    if _SCHOOL_SELF_RE.search(text) and not adult:
        return True
    school = any(word.startswith(_SCHOOL_WORDS) for word in words) or bool(_PUPIL_RE.search(text))
    if school and not adult and not _REUNION_RE.search(text):
        return True
    graduation = any(word.startswith(_GRADUATION) for word in words)
    university = any(word.startswith(_UNIVERSITY) for word in words)
    if graduation and not university and not _REUNION_RE.search(text):
        return True  # выпускной — школьный, если не назван вуз и это не встреча выпускников
    if _KID_GIVE_RE.search(text) and not any(word.startswith(_ADULT_FAMILY) for word in words):
        return True
    return bool(_PARENTS_ALLOW_RE.search(text))


def _driving_words(text: str) -> bool:
    """Вождение без слова «руль»: «мне потом вести», «на самокате домой, полбокала можно?»."""
    if _LEAD_RE.search(text) or _JAM_RE.search(text) or _LICENSE_RE.search(text):
        return True
    drink = _DRINK_CUE_RE.search(text) is not None
    if _DRIVER_RE.search(text) and (drink or _PERMISSION_RE.search(text)):
        return True
    vehicle = _VEHICLE_RE.search(text) is not None
    if drink and (vehicle or _BEFORE_TRIP_RE.search(text)):
        return True
    after = _AFTER_DRINK_RE.search(text) is not None
    if after and vehicle:
        return True  # «после вина можно сесть за мотоцикл?»
    # «Выпью и поеду», «в каршеринге домой поеду, бокал не страшно?» — питьё и дорога; на такси,
    # метро или пешком — не вождение: «после бокала поеду домой на такси».
    ride = _RIDE_RE.search(text) is not None and _NOT_DRIVING_RE.search(text) is None
    return ride and (after or (drink and _HOMEWARD_RE.search(text) is not None))


def _medical_words(text: str, words: list[str]) -> bool:
    """Болезнь окольно: орган с симптомом, сахар крови, «будущей маме», врач запретил, срок
    беременности именительным, лекарство за словом приёма."""
    if _ORGAN_STATE_RE.search(text) or _EXPECTING_RE.search(text):
        return True
    if _DOCTOR_RE.search(text) and not _doctor_on_pairing(words):
        return True
    if _DRUG_INTAKE_RE.search(text) or _ILLNESS_RE.search(text) or _TOOTH_RE.search(text):
        return True
    for match in _TERM_NOMINATIVE_RE.finditer(text):
        if match.group(1) is None or not _wine_age_follows(text, match.end()):
            return True
    return bool(_BLOOD_SUGAR_RE.search(text)) and not any(
        word.startswith(_BERRY_SUGAR) for word in words
    )


#: Врач как советчик о еде: «сосед врач сказал, что оно хорошо к шашлыку» — не о здоровье, если
#: рядом нет ни разрешения, ни питья, ни пользы.
_DOCTOR_HEALTH = _fold(
    ("можно", "нельзя", "разреш", "запрет", "пить", "пью", "выпи", "здоров", "вред", "польз",
     "лечен", "доз", "бокал", "таблет", "лекарств", "болез", "болит", "болен", "больн", "давлен",
     "сердц", "печен", "желуд", "сосуд")
)  # fmt: skip


def _doctor_on_pairing(words: list[str]) -> bool:
    return _pairing_preposition(words) and not any(
        word.startswith(_DOCTOR_HEALTH) for word in words
    )


def _health_words(text: str) -> bool:
    """Вино ради действия на тело: расслабиться, уснуть на ночь (с питьём рядом); доза вином
    за срок."""
    if _PERIOD_DOSE_RE.search(text):
        return True  # «сколько вина в неделю безопасно»
    for match in _RELAX_RE.finditer(text):
        if match.group(0).startswith("расслаб") or _DRINK_CUE_RE.search(text):
            return True
    return False


def _is_homonym(word: str) -> bool:
    return word.startswith(_BARRIER_HOMONYMS)


def _has_word_with_stem(words: list[str], stems: tuple[str, ...]) -> bool:
    """Слово с основой барьера: по началу слова, а длинная основа — и внутри слова."""
    for word in words:
        if _is_homonym(word):
            continue
        for stem in stems:
            if word.startswith(stem) or (len(stem) >= _INFIX_MIN and stem in word):
                return True
    return False


def _inside_homonym(text: str, start: int, length: int) -> bool:
    left = text.rfind(" ", 0, start) + 1
    right = text.find(" ", start + length)
    word = text[left:] if right == -1 else text[left:right]
    return _is_homonym(word)


def _has_phrase(text: str, phrases: tuple[str, ...]) -> bool:
    """Фраза барьера в тексте — но не внутри слова, которое ею не является («дозаж»)."""
    for phrase in phrases:
        position = text.find(phrase)
        while position != -1:
            if not _inside_homonym(text, position, len(phrase)):
                return True
            position = text.find(phrase, position + 1)
    return False


@cache
def _gapped_pattern(first: str, second: str) -> re.Pattern[str]:
    """Первое слово — с начала слова: «насколько оно терпкое, стоит ли…» — не «сколько стоит»."""
    return re.compile(r"\b" + first + r"(?:\s+\S+){0," + str(_GAP_WORDS) + r"}\s+" + second)


def _infinitive_follows(text: str, end: int) -> bool:
    """Инфинитив сразу или через местоимение: «сколько стоит его выдержать» — тоже «следует»."""
    rest = text[end:].split(maxsplit=2)
    if rest and rest[0] in _OBJECT_PRONOUNS:
        rest = rest[1:]
    return bool(rest) and rest[0].endswith(_INFINITIVE_ENDINGS)


#: Местоимения между «стоит» и инфинитивом: «сколько стоит его охлаждать».
_OBJECT_PRONOUNS = frozenset({"его", "ее", "их", "ему", "ей", "им", "это", "эту", "этот"})


def _has_gapped_phrase(text: str, topic: str) -> bool:
    for first, second in _GAPPED_PHRASES.get(topic, ()):
        for match in _gapped_pattern(first, second).finditer(text):
            if second == _STOIT and _infinitive_follows(text, match.end()):
                continue  # «сколько минут стоит дать ему подышать» — подача, а не цена
            if (
                second == _GLASSES
                and _PER_BOTTLE_RE.match(text, match.end())
                and not _dose_cue(text)
            ):
                continue  # «сколько бокалов из бутылки выйдет» — подача, а не доза
            if second == _GLASSES and _INTO_GLASS_RE.search(match.group(0)) and not _dose_cue(text):
                continue  # «сколько наливать в бокал» — сколько налить, а не сколько выпить
            if (
                second == _GLASSES
                and _GUESTS_RE.search(text)
                and not _dose_cue(text)
                and not _DRINK_VERB_RE.search(text)
            ):
                continue  # «сколько бокалов нужно на стол для восьми гостей» — посуда, не доза
            return True
    return False


def _dose_cue(text: str) -> bool:
    """Мера для себя: «мне», «можно», «нормально», «в день», «за вечер»."""
    words = text.split()
    return (
        not _DOSE_WORDS.isdisjoint(words)
        or any(word.startswith(_DOSE_STEMS) for word in words)
        or _has_phrase(text, _DOSE_PHRASES)
    )


def _every_evening_dose(text: str, words: list[str]) -> bool:
    """«Вино каждый вечер — нормально?», «бокал каждый вечер» — доза; «каждый вечер ужинаем с
    рыбой, подойдёт?» — нет: о еде, без питья и без вопроса о мере."""
    if not _has_phrase(text, _EVERY_EVENING):
        return False
    plain = [word for word in words if not _is_homonym(word)]
    if any(word.startswith((*_DRINKING, *_MEASURE)) for word in plain):
        return True
    return not any(word.startswith(_MEALS) for word in plain)


def _stems_hit(words: list[str], stems: tuple[str, ...]) -> set[str]:
    """Какие основы темы нашлись в словах вопроса — по тем же правилам, что `_has_word_with_stem`."""
    return {
        stem
        for word in words
        if not _is_homonym(word)
        for stem in stems
        if word.startswith(stem) or (len(stem) >= _INFIX_MIN and stem in word)
    }


def _medical_relation(words: list[str]) -> bool:
    """Орган назван как орган, а не как блюдо: «при циррозе печени», а не «к куриной печени»."""
    for index, word in enumerate(words):
        if not word.startswith(_ORGANS):
            continue
        window = words[max(0, index - 3) : index]
        if any(w in _MEDICAL_LINK_WORDS or w.startswith(_MEDICAL_LINKS) for w in window):
            return True
        if index and words[index - 1] == "для":
            return True  # «для сердца», «для печени»; «для паштета из печени» — нет
        before = " ".join(words[max(0, index - 4) : index])
        if any(phrase in before for phrase in _MEDICAL_LINK_PHRASES):
            return True
    return False


def _benefit_about_wine(words: list[str]) -> bool:
    """Польза, обращённая к вину: «чем полезен дуб для вина» — агрономия, а не медицина."""
    for index, word in enumerate(words):
        if not word.startswith(("полезн", "польза", "пользу", "пользы", "полезен", "полезно")):
            continue
        if any(w.startswith(_BENEFIT_OBJECTS) for w in words[index + 1 : index + 4]):
            return True
    return False


def _years_of(token: str, words: dict[str, int]) -> int | None:
    years = words.get(token)
    if years is not None:
        return years
    return int(token) if token.isdigit() else None


def _wine_age_follows(text: str, end: int) -> bool:
    """После «N лет» речь о вине: «10-летней выдержки», «5 лет хранения».

    Одно слово «вино» после возраста — ещё не возраст вина, если в вопросе спрашивают
    разрешения: «можно ли в 15 лет вино, если чуть-чуть?» — возраст человека (набор 24.09), а
    «в 5 лет вино раскрывается?» — вина.
    """
    rest = text[end:].lstrip()
    if not rest.startswith(_WINE_AGE_WORDS):
        return False
    return not (rest.split(maxsplit=1)[0] in _WINE_NOUNS and _PERMISSION_RE.search(text))


def _underage_self(text: str) -> bool:
    for match in _SELF_AGE_RE.finditer(text):
        almost, token = match.group(1), match.group(2)
        years = _AGE_WORDS.get(token)
        if years is None:
            try:
                years = int(token)
            except ValueError:
                continue
        # «Мне почти 18», «мне скоро 18» — ещё нет восемнадцати.
        if years > 18 or (years == 18 and not almost):
            continue
        if text[match.end() :].lstrip().startswith(_COUNT_NOUNS):
            continue
        return True
    return False


def _underage(text: str, words: list[str]) -> bool:
    """Назван ли ребёнок младше восемнадцати: числом, словом или ступенью школы."""
    if _underage_self(text):
        return True
    for match in _RELATIVE_AGE_RE.finditer(text):
        try:
            years = int(match.group(1))
        except (TypeError, ValueError):
            continue
        if text[match.end() :].lstrip().startswith(_MONTHS):
            continue  # «сестре на 8 марта» — дата, а не возраст
        if years < 18 or (years == 18 and _ALMOST_RE.search(match.group(0))):
            return True
    for match in _RELATIVE_AGE_WORD_RE.finditer(text):
        years = _AGE_WORDS.get(match.group(1), 99)
        if years < 18 or (years == 18 and _ALMOST_RE.search(match.group(0))):
            return True  # «сыну скоро восемнадцать» — ещё нет
    for match in _PREP_AGE_RE.finditer(text):
        years = _years_of(match.group(1), _AGE_NUMBERS)
        if years is not None and years < 18 and not _wine_age_follows(text, match.end()):
            return True
    for match in _YEARS_OLD_RE.finditer(text):
        years = _years_of(match.group(1), _YEARS_OLD_WORDS)
        if years is not None and years < 18 and not _wine_age_follows(text, match.end()):
            return True
    for index, word in enumerate(words):
        if not word.startswith(_SCHOOL_PHRASES):
            continue
        before = words[max(0, index - 2) : index]
        if any(w.startswith(_SCHOOL_MARKERS) for w in before):
            return True
        # «Я в 10-м классе», «в 9 классе»
        if any(w.isdigit() and 1 <= int(w) <= 11 for w in before):
            return True
    return False


def _pairing_preposition(words: list[str]) -> bool:
    """«К чему-то» или «под что-то» — примета вопроса о еде (повод «к празднику» не в счёт,
    «к кому обратиться» — тоже: это вопрос, куда идти за покупкой, набор 24.09)."""
    for index, word in enumerate(words[:-1]):
        follower = words[index + 1]
        if word in ("к", "под") and not follower.startswith(_OCCASIONS):
            if follower in _NOT_FOOD_AFTER_K:
                continue
            return True
    return False


#: После «к» — не блюдо: к кому, к вам, к нам.
_NOT_FOOD_AFTER_K = frozenset({"кому", "вам", "нам", "тебе", "вас", "нас", "ним", "нему", "ней"})


def _topic_hit(topic: str, text: str, words: list[str]) -> bool:
    if topic == "minors":
        # «Без детей отметим» — ребёнка в вопросе нет; остальной текст проверяется как обычно.
        text = _NO_CHILDREN_RE.sub(" ", text)
        words = text.split()
    return (
        _has_word_with_stem(words, MARKERS.get(topic, ()))
        or not _EXACT.get(topic, frozenset()).isdisjoint(words)
        or _has_phrase(text, PHRASES.get(topic, ()))
        or _has_gapped_phrase(text, topic)
        or (topic == "price" and _CURRENCY_RE.search(text) is not None)
        or (
            topic == "health"
            and (
                _every_evening_dose(text, words) or _bottle_dose(text, words) or _health_words(text)
            )
        )
        or (
            topic == "minors"
            and (_school_age(text, words) or _hiding(text, words) == "minors" or _person_age(text))
        )
        or (topic == "medical" and _medical_words(text, words))
        or (
            topic == "addiction"
            and (_habitual_drinking(text, words) or _hiding(text, words) is not None)
        )
        or (topic == "sobriety" and _hangover(text, words))
        or (topic == "driving" and _driving_words(text))
    )


def _excused(topic: str, text: str, words: list[str], *, dish: bool) -> bool:
    """Исключения «Лозы»: слово темы есть, но спрашивают о другом."""
    if topic == "purchase":
        if contains_any(text, _PURCHASE_PLACE_MARKERS) or _has_gapped_phrase(text, "purchase"):
            return False  # «где купить», «куплю где», «с доставкой» — отказ всегда
        if not {"опт", "оптом"}.isdisjoint(words) or any(w.startswith("оптов") for w in words):
            return False  # «купить оптом для кафе» — способ покупки, отказ всегда
        if _provenance(text, words):
            return True  # «вино из магазина у дома — чем оно интересно?» — откуда, а не где
        # «Хочу купить вино к борщу» — вопрос «какое», а не «где»; «купил кьянти, что
        # приготовить» — покупают еду; «если нет в магазине, что взять» — просьба о замене.
        return (
            dish
            or _pairing_preposition(words)
            or contains_any(text, _FOOD_WORDS)
            or contains_any(text, _REPLACE_WORDS)
            or contains_any(text, _ADVICE_WORDS)
            or contains_any(text, _RESTAURANT_WORDS)
        )
    if topic == "health":
        # «Чем полезен дуб для вина», «водный стресс лозы» — о вине и лозе, а не о человеке.
        hits = _stems_hit(words, MARKERS["health"])
        plant = hits <= {"стресс"} and any(word.startswith(_PLANT_STRESS) for word in words)
        return _benefit_about_wine(words) or (bool(hits) and plant)
    if topic == "addiction":
        return contains_any(text, _NOT_ADDICTION)
    if topic == "driving":
        # «Везу вино на машине», «едем на машине — какое вино взять с собой?» — перевозка вина,
        # если рядом нет ни питья, ни руля, ни дороги домой (набор 24.09).
        return (
            _TRANSPORT_RE.search(text) is not None
            and _DRINK_CUE_RE.search(text) is None
            and _SELF_DRIVE_RE.search(text) is None
        )
    if topic == "medical":
        # «Какими препаратами обрабатывают лозу» — агрономия: из слов медицины только
        # «препарат», фраз медицины нет, рядом — виноградник и его обработка или болезнь, а
        # препарат никто не принимает сам.
        return (
            _stems_hit(words, MARKERS["medical"]) <= _AGRO_MEDICAL
            and not _has_phrase(text, PHRASES["medical"])
            and any(word.startswith(_AGRO_WORDS) for word in words)
            and any(word.startswith(_AGRO_TREATMENT) for word in words)
            and not any(word.startswith(_INTAKE) for word in words)
        )
    return False


#: Покупка в прошлом и магазин как происхождение: «купил в пятёрочке», «вино из магазина».
_PAST_PURCHASE = _fold(("купил", "купила", "купили", "куплен", "покупал"))
_ORIGIN_STORE_RE = re.compile(r"\bиз\s+(?:\S+\s+)?магазин\w*")
#: …но вопрос всё же о покупке: где, есть ли, в наличии, со скидкой, с доставкой.
_PURCHASE_ASK = _fold(("наличи", "продают", "продает", "скидк", "акци", "доставк", "заказ"))


def _provenance(text: str, words: list[str]) -> bool:
    """Магазин назван как происхождение вина, а о покупке не спрашивают: «это вино из магазина у
    дома — чем оно интересно?», «купил в пятёрочке, чем оно интересно?» (набор 24.09)."""
    origin = _ORIGIN_STORE_RE.search(text) is not None
    past = any(word.startswith(_PAST_PURCHASE) for word in words)
    if not origin and not past:
        return False
    if any(word in ("где", "как", "есть") for word in words):
        return False
    return not contains_any(text, _PURCHASE_ASK)


def check(question: str, *, dish: bool = False) -> Refusal | None:
    """Отказ барьера на вопрос или `None`. `dish` — в вопросе названо блюдо справочника.

    Порядок — старшинство тем: возраст, медицина (в том числе орган со связкой болезни),
    зависимость, трезвость, вождение, здоровье, другой алкоголь, покупка, цена, рецепт.
    """
    text = normalize(question)
    if not text:
        return None
    words = text.split()
    if _has_phrase(text, _PREGNANCY):
        # «Жду ребёнка» — беременность, а не возраст: слово «ребёнок» здесь о малыше.
        return refusal("medical")
    term = _PREGNANCY_TERM_RE.search(text)
    if term is not None and not _wine_age_follows(text, term.end()):
        return refusal("medical")  # «я на 5 месяце», а не «на 12 месяце выдержки»
    school = _harmless("minors", text)
    if _underage(school, school.split()):
        return refusal("minors")
    if _medical_relation(words):
        return refusal("medical")
    for topic in TOPIC_ORDER:
        plain = _harmless(topic, text)
        plain_words = plain.split()
        if not _topic_hit(topic, plain, plain_words):
            continue
        if _excused(topic, plain, plain_words, dish=dish):
            continue
        return refusal(topic)
    return None
