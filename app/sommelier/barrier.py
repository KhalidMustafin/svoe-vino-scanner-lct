def refusal(topic: str) -> Refusal:
    """Отказ по теме договора; неизвестная тема — `KeyError`."""
    return Refusal(topic, TEXTS[topic], CHIPS[topic], topic in STICKY)


def _fold(items: tuple[str, ...]) -> tuple[str, ...]:
    """Маркер в том виде, в каком его увидит нормализованный вопрос: «ё» → «е»."""
    return tuple(dict.fromkeys(item.replace("ё", "е") for item in items))


