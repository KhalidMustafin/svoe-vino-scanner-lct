def test_purchase_as_take_needs_a_dish_or_food_word() -> None:
    """«Купить» = «взять» только при блюде или еде; место и способ покупки — отказ всегда."""
    assert topic_of("хочу купить это вино") == "purchase"
    assert topic_of("хочу купить вино к борщу") is None
    assert topic_of("где купить вино к борщу") == "purchase"
    assert topic_of("закажи вино к борщу с доставкой", dish=True) == "purchase"


def test_price_is_refused_even_with_a_dish() -> None:
    """Цену сервис не знает: «к шашлыку подешевле» — отказ, а не подбор без условия."""
    assert topic_of("вино к шашлыку подешевле", dish=True) == "price"
    assert topic_of("недорогое вино к борщу", dish=True) == "price"


