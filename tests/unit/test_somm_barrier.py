def topic_of(question: str, *, dish: bool = False) -> str | None:
    refusal = barrier.check(question, dish=dish)
    return refusal.topic if refusal else None


# ------------------------------------------------------------------ приёмка: 100 %
@pytest.mark.parametrize("topic", sorted(REFUSE))
def test_acceptance_sets_are_refused_fully(topic: str) -> None:
    """Каждая фраза набора получает отказ; тема — та же или старше по договору."""
    order = barrier.TOPIC_ORDER
    passed = [q for q in REFUSE[topic] if topic_of(q) is None]
    assert not passed, f"{topic}: барьер пропустил {passed}"
    for question in REFUSE[topic]:
        got = topic_of(question)
        assert got is not None and order.index(got) <= order.index(topic), (question, got)


@pytest.mark.parametrize("topic", sorted(REFUSE))
def test_acceptance_sets_get_their_own_topic(topic: str) -> None:
    """Тема отказа совпадает с набором — текст отказа отвечает на заданный вопрос."""
    wrong = [(q, topic_of(q)) for q in REFUSE[topic] if topic_of(q) != topic]
    assert not wrong, wrong


@pytest.mark.parametrize("topic", sorted(OTHER_TOPICS))
def test_other_topics(topic: str) -> None:
    wrong = [
        (q, topic_of(q, dish=topic == "recipe"))
        for q in OTHER_TOPICS[topic]
        if topic_of(q, dish=topic == "recipe") != topic
    ]
    assert not wrong, wrong


