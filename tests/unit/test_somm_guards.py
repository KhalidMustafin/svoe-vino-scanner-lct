def test_нота_рядом_со_словом_пакета_пересказ():
    rule = "Минеральность к морскому"
    assert LOCK.descriptors("Минеральность дополняет морские ноты блюда.", rule) == []
    assert LOCK.descriptors("Морской оттенок вина.", rule) == []
    # у каждого вхождения нужен свой сосед из пакета; «вина» короче пяти букв
    assert LOCK.descriptors("Морские ноты и ноты вишни.", rule) == ["вишня", "нота"]
    assert LOCK.descriptors("Морские ноты и ноты танина.", rule) == ["нота"]
    assert LOCK.descriptors("Ноты вина спорят с бульоном.", "Вина подборки") == ["нота"]
    assert LOCK.descriptors("Минеральность дополняет морские ноты.", "Кислотность к жирному") == [
        "нота"
    ]
    # сосед — только из своего предложения: «Рислинг» пакета в прошлом предложении не в счёт
    package = "Вино: Рислинг. Минеральность к морскому"
    assert LOCK.descriptors("Подходит Рислинг. Ноты вина перекликаются с суши.", package) == [
        "нота"
    ]
    assert LOCK.descriptors("Подходит Рислинг: морские ноты суши.", package) == []
    # сосед-аромат пересказом не делает, даже если это блюдо пакета
    dish = "Блюдо: Шоколад — подходит; за: Общий ароматический тон"
    assert LOCK.descriptors("В вине слышны ноты шоколада.", dish) == ["нота"]
    assert LOCK.descriptors("Общий ароматический тон: ноты шоколада.", dish) == ["нота"]


def test_соль_и_виноград_родовые_а_блюдо_ловится_другим_словом():
    assert LOCK.violations("Игристость уравновешивает соль блюда.", ["Борщ"]) == []
    assert LOCK.violations("В них тот же сорт винограда.", ["Борщ"]) == []
    assert LOCK.violations("К лососю слабой соли подходит.", ["Борщ"]) == ["лососю", "слабой"]
    assert LOCK.violations("Подходит к солёной рыбе.", ["Борщ"]) == ["соленой"]
    # родовые — только эти словоформы целиком: «к винограду», «с виноградом» — блюдо
    assert LOCK.violations("Подходит к сыру и винограду.", ["Борщ"]) == ["винограду"]
    assert LOCK.violations("Сыр с виноградом.", ["Борщ"]) == ["виноградом"]
