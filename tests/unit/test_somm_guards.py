class TestGuards:
    def test_нормальный_пересказ_проходит(self):
        assert check("К борщу — да, с оговоркой: бульон подчёркивает терпкость Саперави.") is None

    def test_выдуманное_число_бракуется(self):
        assert check("Это вино 1975 года, к борщу оно подходит с оговоркой.") == "numbers"

    def test_думание_вырезается(self):
        raw = (
            "<think>борщ жирный...</think>К борщу — да, с оговоркой: бульон подчёркивает терпкость."
        )
        assert check(raw) is None
        assert "<think>" not in guards.clean(raw)
        assert guards.clean(raw).startswith("К борщу")

    def test_мета_преамбула_бракуется(self):
        text = "Конечно, вот пересказанное в разговорной форме: к борщу вино подходит с оговоркой."
        assert check(text) == "preamble"

    def test_обрыв_на_полуслове_бракуется(self):
        assert check("Я расскажу вам о в") is not None
        assert check("К борщу это вино подходит, но бульон и") == "cutoff"

    def test_запрещённое_бракуется_целиком(self):
        """У «Лозы» фраза вычёркивалась; здесь текст уходит в шаблон — журналу его не отдать."""
        text = "К борщу — да, с оговоркой. Красное вино полезно для сердца."
        assert check(text) == "legal"


