def _loza_lock() -> EntityLock:
    """Словарь заглушек плюс блюда «Лозы», которых в заглушке нет: «Крабы», «Хачапури»."""
    data = json.loads((FIXTURES / "vocab.json").read_text(encoding="utf-8"))
    data["dishes"] = [*data["dishes"], "крабы", "хачапури", "сёмга", "суши"]
    return EntityLock.from_mapping(data)


LOZA_LOCK = _loza_lock()


def loza_allowed() -> list[str]:
    return [LOZA_TRUSTED, *LOZA_ENTITIES]


class TestЗамокСущностей:
    def test_словарь_подозрений_собран(self):
        assert LOCK.size > 100

    def test_выдуманное_блюдо_ловится(self):
        """Тот самый случай «Лозы»: краба в подборе не было."""
        text = "К вину Рислинг от Agora подойдут жирные овощные салаты или салат из краба."
        assert "краба" in LOZA_LOCK.violations(text, loza_allowed())

    def test_дописанный_способ_приготовления_ловится(self):
        """«Сёмга» честная, «на гриле» — добавленный факт."""
        assert LOZA_LOCK.violations("К этому вину идёт сёмга на гриле и овощи.", loza_allowed())

    def test_честный_пересказ_проходит(self):
        text = (
            "К этому рислингу хорошо идут малосольная сёмга, блины с икрой и "
            "селёдка под шубой — вино освежает вкус после жирного куска."
        )
        assert LOZA_LOCK.violations(text, loza_allowed()) == []

    def test_обобщения_разрешены(self):
        """Модель вправе сказать «к рыбе», не перечисляя блюда."""
        text = "Это вино хорошо к рыбе, овощам и лёгким закускам — живая кислотность."
        assert LOZA_LOCK.violations(text, loza_allowed()) == []

    def test_словоформы_не_считаются_чужими(self):
        text = "Подайте с малосольной сёмгой или с блинами с икрой."
        assert LOZA_LOCK.violations(text, loza_allowed()) == []

    def test_имена_пакета_разрешены(self):
        """У «Лозы» — «слова вопроса разрешены»; вопроса модель больше не видит, пакет — да."""
        assert LOZA_LOCK.violations("Рислинг раскроется ярче.", loza_allowed()) == []

    @pytest.mark.parametrize("dish", ["борщ", "шашлык", "хачапури", "устрицы", "медовик"])
    def test_чужое_блюдо_справочника_ловится(self, dish):
        """Имя из словаря — не оправдание: важна принадлежность ответу."""
        text = f"Отличная пара — {dish}, вино его прекрасно дополнит."
        assert LOZA_LOCK.violations(text, loza_allowed())

    def test_чужая_винодельня_ловится(self):
        text = "Возьмите вино от Фанагории — оно подойдёт лучше."
        assert LOZA_LOCK.violations(text, loza_allowed())

    def test_без_словаря_замок_молчит(self):
        """Отсутствие словаря не роняет голос: пустой замок ничего не бракует."""
        assert EntityLock(PlainVocab()).violations("салат из краба", []) == []

    def test_пустой_словарь_не_мешает_следующему_замку(self):
        """У «Лозы» — «провал сборки словаря не запоминается»: у нас словарь — данные замка."""
        assert EntityLock(PlainVocab()).size == 0
        assert _loza_lock().violations("салат из краба", []) == ["краба"]


class TestЖиваяРечьПроходит:
    """Замок обязан пропускать обиход: иначе он съедает то, ради чего стоит."""

    @pytest.mark.parametrize(
        "text",
        [
            "Откройте бутылку за пару часов до подачи.",
            "Пара бокалов к ужину — то, что нужно.",
            "Хорошо к рыбе, овощам и лёгким закускам.",
        ],
    )
    def test_обиходная_фраза_не_бракуется(self, text):
        assert LOZA_LOCK.violations(text, loza_allowed()) == []

    @pytest.mark.parametrize(
        "text",
        [
            "Свежая кислотность поддержит блюдо.",
            "Подавайте холодным — холодное белое тут к месту.",
            "Сливочная текстура и дубовая нота.",
            "Плотное тело, спелые танины, яркий аромат.",
        ],
    )
    def test_вкусовое_слово_не_считается_сущностью(self, text):
        assert LOZA_LOCK.violations(text, loza_allowed()) == []

    @pytest.mark.parametrize(
        "text,name",
        [
            ("Подайте с холодцом и квашеной капустой.", "холодцом"),
            ("Подойдут свежие устрицы.", "устрицы"),
        ],
    )
    def test_блюдо_рядом_с_вкусовым_словом_ловится(self, text, name):
        assert name in LOZA_LOCK.violations(text, loza_allowed())

    def test_способ_приготовления_из_двух_слов_ловится(self):
        """«На пару» — добавленный факт, хотя каждое слово по отдельности нет."""
        assert "на пару" in LOZA_LOCK.violations("Возьмите рыбу на пару.", loza_allowed())

    def test_цвет_вина_не_роза(self):
        """«Розовое» — стиль, а не аромат розы; «горький шоколад» не делает «горький» блюдом."""
        assert LOCK.descriptors("Розовое вино к борщу — с оговоркой.", "") == []
        assert LOCK.violations("Горький привкус бульона.", ["бульон"]) == []


