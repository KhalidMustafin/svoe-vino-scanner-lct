def softer_facts(*, wines: bool = True):
    """«Помягче» без блюда: три Пино Нуар или пустая подборка с нотой «Сомелье у полки»."""
    public = dict(facts_event("ask_dish_check_live.ndjson"))
    public.update(intent="softer", dishes=[], wines_title="Помягче" if wines else None)
    if not wines:
        public.update(wines=[], compare=None, notice_149=None)
    template = (
        "Помягче — три вина других виноделен того же стиля."
        if wines
        else "Вин помягче того же стиля в каталоге не нашлось."
    )
    return build_facts(public, template=template)


